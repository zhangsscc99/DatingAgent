#!/usr/bin/env node
/**
 * F04 — inject build metadata once, at build time.
 *
 * Writes `backend/src/generated/build-info.ts` (gitignored) so the HTTP layer
 * only ever reads constants. The server must never shell out to git or stat
 * files per request.
 *
 * Overridable for CI: GIT_SHA, BUILD_TIME (ISO-8601).
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(repoRoot, 'backend', 'src', 'generated');
const outFile = path.join(outDir, 'build-info.ts');

function readVersion() {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'backend', 'package.json'), 'utf8'));
    const version = typeof pkg.version === 'string' ? pkg.version.trim() : '';
    return version || '0.0.0';
  } catch (err) {
    console.warn(`[build-info] cannot read backend/package.json: ${err.message}`);
    return '0.0.0';
  }
}

function readGitSha() {
  const fromEnv = process.env.GIT_SHA?.trim();
  if (fromEnv) return fromEnv.slice(0, 40);
  try {
    const sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: repoRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return sha || 'unknown';
  } catch {
    return 'unknown';
  }
}

function readBuildTime() {
  const fromEnv = process.env.BUILD_TIME?.trim();
  if (fromEnv) {
    const parsed = new Date(fromEnv);
    if (!Number.isNaN(parsed.getTime())) return parsed.toISOString();
    console.warn(`[build-info] ignoring invalid BUILD_TIME="${fromEnv}"`);
  }
  return new Date().toISOString();
}

const version = readVersion();
const gitSha = readGitSha();
const buildTime = readBuildTime();

const banner = `// AUTO-GENERATED by scripts/gen-build-info.mjs — do not edit, do not commit.\n`;

const body = `${banner}export interface BuildInfo {
  version: string;
  gitSha: string;
  buildTime: string;
}

export const BUILD_INFO: BuildInfo = {
  version: ${JSON.stringify(version)},
  gitSha: ${JSON.stringify(gitSha)},
  buildTime: ${JSON.stringify(buildTime)},
};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, body, 'utf8');

// Also refresh the compiled copy when a build already exists, so
// scripts/refresh-version.sh can re-bake the CURRENT head into dist/ without a
// full `tsc` rebuild — the baked fallback layer then agrees with the repo read.
const distFile = path.join(repoRoot, 'backend', 'dist', 'generated', 'build-info.js');
if (fs.existsSync(path.dirname(distFile))) {
  const jsBody = `${banner}export const BUILD_INFO = {
    version: ${JSON.stringify(version)},
    gitSha: ${JSON.stringify(gitSha)},
    buildTime: ${JSON.stringify(buildTime)},
};
`;
  fs.writeFileSync(distFile, jsBody, 'utf8');
  console.log(`[build-info] dist copy refreshed -> ${path.relative(repoRoot, distFile)}`);
}

console.log(`[build-info] ${version} @ ${gitSha} (${buildTime}) -> ${path.relative(repoRoot, outFile)}`);
